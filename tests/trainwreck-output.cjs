const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const folder = path.join(__dirname, '..', 'presets', 'helix-native');
const source = JSON.parse(fs.readFileSync(path.join(folder, '12 Trainwreck Edge Dynamic Plate.hlx')));
const candidate = JSON.parse(fs.readFileSync(path.join(folder, '12 Trainwreck Edge Dynamic Plate v2.hlx')));
assert.equal(candidate.data.meta.name, '12 Wreck DP v2');
assert.equal(source.data.tone.dsp0.outputA.gain, 8);
assert.equal(candidate.data.tone.dsp0.outputA.gain, 5);
candidate.data.tone.dsp0.outputA.gain = source.data.tone.dsp0.outputA.gain;
candidate.data.meta = source.data.meta;
assert.deepEqual(candidate, source, 'only final output gain and metadata change');
console.log('PASS: Trainwreck output reduced 3 dB; all amp, effects, snapshots and controls unchanged.');
